"""
Run the UR3e pick-and-place demo on the real arm, through the lab's control
script (new_ur_control_script.py, exactly as given) and the OnRobot gripper
(simple_gripper_control.py).

    python UR3/ur3_real.py --dry-run   # print what would be sent; no robot
    python UR3/ur3_real.py

STEPS below is the demo: pick a block up off the bench, carry it over, put it
down. jointstatesim.py animates this same list, so rehearse there first. It is
generated by pick_place.py (block position, drop position, gripper length):
re-run `python UR3/pick_place.py` and paste its output over STEPS after
changing those.

SAFETY: keep the physical e-stop in reach and follow the lab's risk assessment
and SWMS. The e-stop is the way to stop the arm: Ctrl+C only stops the script
sending further moves.
"""
import sys

ROS_HOST = "192.168.27.1"      # the lab's ROS bridge (as in new_ur_control_script.py)
ROS_PORT = 9090

# Each step is ('move', name, joint_positions, duration) or ('grip', 'open'/'close').
HOME = [0.0, -1.5708, 0.0, -1.5708, 0.0, 0.0]
STEPS = [
    ('grip', 'open'),
    ('move', 'above pick', [2.27654, -1.47618, 1.12776, -1.22238, -1.5708, -2.43585], 4.9),
    ('move', 'pick', [2.27654, -1.52132, 1.65305, -1.70253, -1.5708, -2.43585], 2.0),
    ('grip', 'close'),
    ('move', 'above pick', [2.27654, -1.47618, 1.12776, -1.22238, -1.5708, -2.43585], 2.0),
    ('move', 'above place', [1.62435, -1.18061, 0.61093, -1.00111, -1.5708, -3.08804], 2.0),
    ('move', 'place', [1.62435, -1.32605, 1.30749, -1.55223, -1.5708, -3.08804], 2.0),
    ('grip', 'open'),
    ('move', 'above place', [1.62435, -1.18061, 0.61093, -1.00111, -1.5708, -3.08804], 2.0),
    ('move', 'home', HOME, 6.2),
]


def joint_state_help(client):
    """Print the joint-state topics rosbridge actually has, to show why none arrived."""
    try:
        topics = [t for t in client.get_topics() if "joint_states" in t]
    except Exception as e:
        print(f"[APP] Could not list topics: {e}")
        return
    if "/ur/joint_states" in topics:
        print("[APP] /ur/joint_states exists but nothing is being published on it: check the UR "
              "driver is running and the External Control program is playing on the teach pendant.")
    elif topics:
        print(f"[APP] No /ur/joint_states topic. Joint-state topics found: {topics}")
    else:
        print("[APP] No joint_states topics at all: the UR driver isn't running on the ROS PC.")


def main():
    if "--dry-run" in sys.argv:
        print(f"move_ur_joint_positions(client, {HOME}, duration=8.0)")
        for step in STEPS:
            if step[0] == 'grip':
                print(f"{step[1]}_gripper(client)")
            else:
                print(f"move_ur_joint_positions(client, {step[2]}, duration={step[3]})  # {step[1]}")
        return

    import roslibpy
    from new_ur_control_script import move_ur_joint_positions   # the lab's script, exactly as given
    from simple_gripper_control import open_gripper, close_gripper

    client = roslibpy.Ros(host=ROS_HOST, port=ROS_PORT)
    client.run()
    try:
        input("[APP] Press ENTER to move to home (slowly), Ctrl+C to quit")
        move_ur_joint_positions(client, HOME, duration=8.0)

        for step in STEPS:
            if step[0] == 'grip':
                print(f"[APP] Gripper: {step[1]}")
                if step[1] == 'close':
                    close_gripper(client)
                else:
                    open_gripper(client)
            else:
                _, name, target_joint_positions, duration = step
                print(f"[APP] Move: {name}")
                move_ur_joint_positions(client, target_joint_positions, duration=duration)

        print("[APP] Done: block moved, arm back at home.")

    except KeyboardInterrupt:
        print("\n[APP] Interrupted by user.")
    except RuntimeError as e:
        print(f"\n[APP] Stopped: {e}")
        if "joint state" in str(e):
            joint_state_help(client)
    finally:
        client.terminate()


if __name__ == '__main__':
    main()
